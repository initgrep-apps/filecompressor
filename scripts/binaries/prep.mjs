#!/usr/bin/env node
import { join } from "node:path";
import {
  exists,
  hostTriple,
  isMain,
  manifestPath,
  parseArgs,
  readJson,
  run,
  validateManifest,
} from "./lib.mjs";

export async function prepTarget(target, root) {
  const manifestFile = manifestPath(root);
  if (!(await exists(manifestFile))) {
    throw new Error(
      `manifest missing: ${manifestFile} — restore scripts/binaries.manifest.json before prepping`,
    );
  }
  let manifest;
  try {
    manifest = readJson(manifestFile);
    validateManifest(manifest);
  } catch (error) {
    throw new Error(`${error.message ?? error} (scripts/binaries.manifest.json)`);
  }
  const targetEntries = manifest.targets?.[target];
  if (!targetEntries) {
    throw new Error(
      `target '${target}' not in manifest (known: ${Object.keys(manifest.targets ?? {}).join(", ") || "none"})`,
    );
  }
  const conf = join(root, "src-tauri", "tauri.conf.json");
  if (await exists(conf)) {
    const { stdout } = await run("grep", ["-c", '"frameworks/', conf]).catch(() => ({ stdout: "0" }));
    if (Number(stdout.trim()) > 0 && !(await exists(join(root, "src-tauri", "frameworks")))) {
      throw new Error(
        `prep: tauri.conf.json references ${stdout.trim()} dylibs under src-tauri/frameworks/ but that directory is absent — frameworks are generated by macOS prep, which lands in Task 2 of docs/superpowers/plans/2026-10-02-sidecar-binaries-release.md; until then run 'bash scripts/bundle-vips-macos.sh && bash scripts/bundle-pdf-macos.sh'`,
      );
    }
  }
  const brewEntries = Object.entries(targetEntries).filter(([, entry]) => entry.source === "brew");
  if (brewEntries.length > 0) {
    const names = brewEntries.map(([name]) => name).join(", ");
    throw new Error(
      `prep: ${names} for ${target} are brew-owned entries with no prep implementation yet — macOS prep lands in Task 2 of docs/superpowers/plans/2026-10-02-sidecar-binaries-release.md; refusing to report success with the binary uninstalled`,
    );
  }
  console.log(
    `prep: macOS prep for ${target} is implemented in Task 2 (plan 2026-10-02-sidecar-binaries-release) — nothing to do yet`,
  );
  return true;
}

if (isMain(import.meta.url)) {
  try {
    const args = parseArgs(process.argv.slice(2));
    const root = args.root ?? process.cwd();
    const target = args.target ?? (await hostTriple());
    if (!target) {
      console.error(
        "FAIL no --target given and host triple could not be detected (see warning above) — pass --target <triple>",
      );
      process.exit(1);
    }
    const ok = await prepTarget(target, root);
    process.exit(ok ? 0 : 1);
  } catch (error) {
    console.error(`FAIL ${error.message ?? error}`);
    process.exit(1);
  }
}