#!/usr/bin/env node
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { isMain, lockPath, parseArgs } from "./lib.mjs";

export const SBOM_FILE = "sbom.json";
export const NOTICES_FILE = "THIRD_PARTY_LICENSES.md";

const LICENSE_BY_ENGINE = {
  ffmpeg: "GPL-2.0-or-later",
  ffprobe: "GPL-2.0-or-later",
  gs: "AGPL-3.0",
  vips: "LGPL-3.0",
  qpdf: "Apache-2.0",
};

const LICENSE_TEXT_POINTER = {
  "GPL-2.0-or-later": "https://www.gnu.org/licenses/old-licenses/gpl-2.0.html",
  "AGPL-3.0": "https://www.gnu.org/licenses/agpl-3.0.html",
  "LGPL-3.0": "https://www.gnu.org/licenses/lgpl-3.0.html",
  "Apache-2.0": "https://www.apache.org/licenses/LICENSE-2.0",
};

export class SbomError extends Error {
  constructor(message) {
    super(message);
    this.name = "SbomError";
  }
}

export function licenseFor(name) {
  const license = LICENSE_BY_ENGINE[name];
  if (license === undefined) {
    throw new SbomError(
      `no license mapping for engine '${name}' — refusing to emit an SBOM entry with an unknown \\
       license. Add '${name}' to LICENSE_BY_ENGINE in scripts/binaries/sbom.mjs with its real \\
       SPDX id before shipping it`,
    );
  }
  return license;
}

function componentKey(name, version) {
  return `${name}@${version}`;
}

function sourceOf(entry) {
  if (entry.source === "brew") {
    const formula = entry.formula ? ` (Homebrew formula: ${entry.formula})` : "";
    return `brew${formula}`;
  }
  return entry.url ?? "unknown";
}

function summariseArtifacts(component) {
  const digests = new Set(component.artifacts.map((artifact) => artifact.sha256));
  component.sha256 = digests.size === 1 ? [...digests][0] : null;
  component.sha256Agrees = digests.size === 1;
  const sources = [...new Set(component.artifacts.map((artifact) => artifact.source))];
  component.source = sources.join(" | ");
}

export function buildComponents(lock) {
  const byKey = new Map();
  for (const [triple, entries] of Object.entries(lock?.targets ?? {})) {
    for (const [name, entry] of Object.entries(entries ?? {})) {
      const version = entry?.version;
      if (typeof version !== "string" || version.length === 0) {
        throw new SbomError(
          `lock entry ${triple}/${name} has no version — an SBOM component without a version \\
           cannot be matched against a vulnerability database`,
        );
      }
      const key = componentKey(name, version);
      const artifact = {
        triple,
        source: sourceOf(entry),
        sha256: typeof entry.sha256 === "string" ? entry.sha256 : null,
      };
      const existing = byKey.get(key);
      if (existing) {
        existing.targets.push(triple);
        existing.artifacts.push(artifact);
        continue;
      }
      byKey.set(key, {
        name,
        version,
        license: licenseFor(name),
        source: artifact.source,
        sha256: artifact.sha256,
        targets: [triple],
        artifacts: [artifact],
      });
    }
  }
  for (const component of byKey.values()) {
    summariseArtifacts(component);
  }
  const components = [...byKey.values()];
  if (components.length === 0) {
    throw new SbomError(
      "the lock lists no components — run 'yarn binaries:all' first, then re-run 'yarn sbom'",
    );
  }
  components.sort((left, right) =>
    left.name === right.name
      ? left.version.localeCompare(right.version)
      : left.name.localeCompare(right.name),
  );
  return components;
}

function sha256Note(component) {
  if (component.sha256Agrees && component.sha256) {
    return component.sha256;
  }
  if (component.artifacts.every((artifact) => artifact.sha256 === null)) {
    return "not published by the vendor (locally built)";
  }
  return "differs per target — see the per-target digests below";
}

export function renderMarkdown(components, lock) {
  const lines = [
    "# Third-Party Licenses",
    "",
    "Generated by `yarn sbom` from `scripts/binaries.lock.json`. Do not edit by hand: regenerate",
    "it whenever the lock changes, and fail the release if it is stale.",
    "",
    `Artifacts verified: ${lock.generated}`,
    "",
    "Every value below is a pure function of `scripts/binaries.lock.json`, so re-running `yarn",
    "sbom` on an unchanged lock reproduces this file byte for byte. That is what lets a release",
    "job fail the build when this notice is out of date with the lock.",
    "",
    `Components: ${components.length}`,
    "",
  ];
  for (const component of components) {
    lines.push(
      `## ${component.name} ${component.version}`,
      "",
      `- Version: ${component.version}`,
      `- License: ${component.license}`,
      `- License text: ${LICENSE_TEXT_POINTER[component.license]}`,
      `- Source: ${component.source}`,
      `- SHA-256: ${sha256Note(component)}`,
      `- Targets: ${component.targets.join(", ")}`,
      ...component.artifacts.map(
        (artifact) => `  - ${artifact.triple}: ${artifact.source}${
          artifact.sha256 ? ` (${artifact.sha256})` : " (no vendor digest)"
        }`,
      ),
      "",
    );
  }
  lines.push(
    "## Application license",
    "",
    "This application is distributed under GPLv3. The components above are redistributed as",
    "separate executables invoked as child processes; each remains under its own license, whose",
    "full text is linked above.",
    "",
  );
  return lines.join("\n");
}

export async function generate({ root, lockPath: override } = {}) {
  const resolvedRoot = root ?? process.cwd();
  const resolvedLock = override ?? lockPath(resolvedRoot);
  let raw;
  try {
    raw = await readFile(resolvedLock, "utf8");
  } catch (error) {
    throw new SbomError(
      `cannot read the binaries lock at ${resolvedLock} (${error.message ?? error}) — run \\
       'yarn binaries:all' to produce it, then re-run 'yarn sbom'`,
    );
  }
  let lock;
  try {
    lock = JSON.parse(raw);
  } catch (error) {
    throw new SbomError(
      `cannot parse ${resolvedLock} (${error.message ?? error}) — fix or regenerate the lock`,
    );
  }

  if (typeof lock?.generated !== "string" || lock.generated.length === 0) {
    throw new SbomError(
      `${resolvedLock} has no 'generated' timestamp — an SBOM that cannot say when its \
       artifacts were verified is not auditable. Regenerate the lock with 'yarn binaries:all'`,
    );
  }

  const components = buildComponents(lock);
  const sbom = {
    generated: lock.generated,
    components,
  };
  const markdown = renderMarkdown(components, lock);

  await mkdir(resolvedRoot, { recursive: true });
  await writeFile(join(resolvedRoot, SBOM_FILE), `${JSON.stringify(sbom, null, 2)}\n`);
  await writeFile(join(resolvedRoot, NOTICES_FILE), markdown);
  return { sbom, components, markdown, sbomPath: join(resolvedRoot, SBOM_FILE), noticesPath: join(resolvedRoot, NOTICES_FILE) };
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const root = args.root ?? process.cwd();
  try {
    const result = await generate({ root });
    console.log(`sbom: wrote ${result.sbomPath}`);
    console.log(`sbom: wrote ${result.noticesPath}`);
    console.log(
      `sbom: ${result.components.length} component(s) — ${result.components
        .map((component) => `${component.name}@${component.version} (${component.license})`)
        .join(", ")}`,
    );
  } catch (error) {
    console.error(`FAIL ${error.message ?? error}`);
    process.exit(1);
  }
}

if (isMain(import.meta.url)) {
  await main();
}
